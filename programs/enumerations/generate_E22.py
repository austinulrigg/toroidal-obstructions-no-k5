"""E22: the remaining components with five neighbours (Proposition 6.7).

The program's names: p1, p2 are the twins on abc and q1, q2 those on ade.
A component of G - V(Psi_3) meets all of a, b, c, d, e, with bridge B, and
the proof reduces G to Psi_3 + B or Psi_3 + B + bd. B is a part of
Construction 3.17 with attachments a, b, c, d, e and added edges ab, ac,
ad, ae, and also bd when bd is present, in which case the retained K3,3
subdivision must use bd (Corollary 6.6).

Symmetry: the permutations of b, c, d, e generated by (b c), (d e) and
(b d)(c e) fix Psi_3 and the added edges ab, ac, ad, ae; with bd, the
subgroup {id, (b d)(c e)} also fixes bd. Construction 3.17 commutes with
relabelling the attachments by such a permutation, so the placements of
the attachments are taken up to the 72 symmetries of K3,3 and this group.

Classification: for each part, the one-step allowed operations of
Section 3 are tried in order; the first that keeps B' + added edges
nonplanar gives an edge e of B with G - e or G / e containing Psi_3 + B'
(for a deleted interior vertex, one of its edges is deleted), and
multi_genus confirms that this graph has genus at least two. The other
parts are classified by psi2_runs.fast_outcomes. A candidate with two twin
triples disjoint or sharing two vertices is also recorded with a
certificate. The proof finds T20 and T23 without bd and nothing with bd.

The records are written in parts of at most 20,000 (folders with_bd_01,
..., without_bd_01, ...). Run as
    python generate_E22.py FOLDER with_bd
    python generate_E22.py FOLDER without_bd
    python generate_E22.py FOLDER summarize
"""
import itertools
import json
import sys
import time
from collections import Counter
from multiprocessing import Pool
from pathlib import Path

import networkx as nx

import common
import enumeration as el
import psi2_runs as ext

ROOTS = tuple("abcde")
PSI3 = {"p1": "abc", "p2": "abc", "q1": "ade", "q2": "ade"}
STAR = [("a", "b"), ("a", "c"), ("a", "d"), ("a", "e")]
CHUNK = 20000


def perm_group(gens):
    ident = {x: x for x in ROOTS}
    group = {tuple(sorted(ident.items()))}
    frontier = [ident]
    while frontier:
        new = []
        for g in frontier:
            for h in gens:
                k = {x: h[g[x]] for x in ROOTS}
                key = tuple(sorted(k.items()))
                if key not in group:
                    group.add(key)
                    new.append(k)
        frontier = new
    return [dict(g) for g in sorted(group)]


def mk(cycles):
    m = {x: x for x in ROOTS}
    for cyc in cycles:
        for i, x in enumerate(cyc):
            m[x] = cyc[(i + 1) % len(cyc)]
    return m


GROUP_NOBD = perm_group([mk(["bc"]), mk(["de"]), mk(["bd", "ce"])])
GROUP_BD = [g for g in GROUP_NOBD if {g["b"], g["d"]} == {"b", "d"}]


def canonical(pl):
    return min(el.transform(pl, a) for a in el.AUTS)


def relabel_placement(pl, sigma):
    idx = {x: i for i, x in enumerate(ROOTS)}
    m = [idx[sigma[x]] for x in ROOTS]
    branches, paths = pl
    nb = tuple(m[i] if i >= 0 else -1 for i in branches)
    np_ = tuple(tuple(m[i] for i in p) for p in paths)
    return (nb, np_)


def reduced_classes(group):
    reps, raw = el.placement_classes(5)
    keep = []
    for pl0, orbit in reps:
        if all(canonical(relabel_placement(pl0, g)) >= pl0 for g in group):
            keep.append(pl0)
    return keep, len(reps), raw


def gen_parts(spec, placements):
    """Parts up to label-preserving isomorphism, stored compactly as sorted
    edge lists (interior vertices renamed u0, u1, ...)."""
    buckets, parts = {}, []
    st = Counter()

    def graph_of(edges):
        H = nx.Graph()
        H.add_nodes_from(spec.roots)
        H.add_edges_from(edges)
        return H
    for pl in placements:
        res = el.build_retained(pl, spec)
        if res is None:
            continue
        K, part = res
        st["valid retained subdivisions"] += 1
        for P in el.completions(part, spec.roots):
            st["recipes"] += 1
            key = el.rooted_key(P, spec.roots)
            if any(el.rooted_isomorphic(P, graph_of(parts[j]), spec.roots) for j in buckets.get(key, [])):
                continue
            buckets.setdefault(key, []).append(len(parts))
            Q = el.relabel_interior(P, spec.roots)
            parts.append(tuple(sorted(tuple(sorted(map(str, e))) for e in Q.edges())))
    st["parts up to label-preserving isomorphism"] = len(parts)
    return parts, dict(st)


def whole(P, bd):
    G = nx.Graph()
    for t, nb in PSI3.items():
        G.add_edges_from((t, v) for v in nb)
    G.add_edges_from(P.edges())
    if bd:
        G.add_edge("b", "d")
    return G


def bridge_minor(job):
    """The first one-step allowed operation keeping P' + D nonplanar, as an
    edge operation on G, or None."""
    idx, pedges, dedges = job
    P = nx.Graph()
    P.add_nodes_from(ROOTS)
    P.add_edges_from(pedges)
    for (op, args), H in el.allowed_operations(P, ROOTS):
        T = H.copy()
        T.add_edges_from(dedges)
        if not nx.check_planarity(T)[0]:
            if op == "delete vertex":
                v = args[0]
                x = sorted(P[v], key=str)[0]
                return idx, ("delete", (v, x))
            if op == "delete edge":
                return idx, ("delete", tuple(args))
            return idx, ("contract", tuple(args))
    return idx, None


def classify_all(pool, parts, bd, dedges):
    """parts: edge lists of P. Returns (graphs, outcomes, number excluded by
    an allowed operation on P, number classified as whole graphs)."""
    graphs = []
    for edges in parts:
        P = nx.Graph()
        P.add_nodes_from(ROOTS)
        P.add_edges_from(edges)
        graphs.append(whole(P, bd))
    ops = [None] * len(parts)
    jobs = [(i, [list(e) for e in edges], dedges) for i, edges in enumerate(parts)]
    for i, r in pool.imap_unordered(bridge_minor, jobs, chunksize=64):
        ops[i] = r
    outcomes = [None] * len(parts)
    cand = [i for i in range(len(parts)) if ops[i] is not None]
    for s in range(0, len(cand), 5000):
        block = cand[s:s + 5000]
        minors = []
        for i in block:
            op, e = ops[i]
            G = graphs[i]
            minors.append(el.gr.delete_edge(G, e) if op == "delete" else el.gr.contract_edge(G, e))
        flags = el.genus_above_one(minors)
        for i, fl in zip(block, flags):
            if fl:
                op, e = ops[i]
                outcomes[i] = {"outcome": "proper nontoroidal minor", "operation": op,
                               "edge": [str(x) for x in el.edge_key(e)],
                               "found by": "allowed operation on P keeping P'+D nonplanar"}
    rest = [i for i in range(len(parts)) if outcomes[i] is None]
    if rest:
        res = ext.fast_outcomes([graphs[i] for i in rest])
        for i, o in zip(rest, res):
            outcomes[i] = o
    return graphs, outcomes, len(cand), len(rest)


def summarize(out):
    total = {"cases": {}, "folders": [], "outcomes": Counter(), "survivors": []}
    for case in ("with_bd", "without_bd"):
        cs = json.load(open(out / ("%s_generation.json" % case)))
        total["cases"][case] = cs
        for name in cs["folders"]:
            summ = json.load(open(out / name / "summary.json"))
            total["folders"].append(name)
            total["outcomes"].update(summ["outcomes"])
            total["survivors"] += [dict(x, folder=name) for x in summ["survivors"]]
    found = {c: sorted({x["catalogue"] for x in total["survivors"] if x["folder"].startswith(c)},
                       key=lambda t: int(t[1:])) for c in ("without_bd", "with_bd")}
    summary = {"item": "E22", "where": "Proposition 6.7",
               "cases": total["cases"], "folders": total["folders"],
               "candidates": sum(total["outcomes"].values()), "outcomes": dict(total["outcomes"]),
               "survivors": total["survivors"], "catalogue graphs found by case": found,
               "targets in the text": {"without_bd": ["T20", "T23"], "with_bd": []}}
    summary["agrees with the text"] = found == summary["targets in the text"]
    json.dump(summary, open(out / "summary.json", "w"), indent=1)
    return summary


if __name__ == "__main__":
    out = Path(sys.argv[1])
    which = sys.argv[2] if len(sys.argv) > 2 else "summarize"
    out.mkdir(parents=True, exist_ok=True)
    if which == "summarize":
        s = summarize(out)
        print(json.dumps({k: s[k] for k in ("candidates", "outcomes", "catalogue graphs found by case",
                                             "agrees with the text")}, indent=1))
        sys.exit(0)
    t0 = time.time()
    pool = Pool(common.workers())       # started before the large data exist
    case, bd, group = {"with_bd": ("with_bd", True, GROUP_BD),
                       "without_bd": ("without_bd", False, GROUP_NOBD)}[which]
    dedges = STAR + ([("b", "d")] if bd else [])
    spec = el.Spec(ROOTS, c_edges=dedges, required=[("b", "d")] if bd else [])
    placements, nclasses, raw = reduced_classes(group)
    parts, st = gen_parts(spec, placements)
    st.update({"root placements": raw, "root placement classes (K3,3)": nclasses,
               "classes up to K3,3 and the symmetries of Psi3 and D": len(placements),
               "symmetry group order": len(group), "specification": spec.payload(), "folders": []})
    print(case, st, round(time.time() - t0), flush=True)
    st["excluded by an allowed operation on P"] = 0
    st["classified as whole graphs"] = 0
    chk = lambda G: ext.section6_violation(G, forbid_five=False)  # noqa: E731
    for c, s0 in enumerate(range(0, len(parts), CHUNK)):
        block = parts[s0:s0 + CHUNK]
        graphs, outcomes, nbridge, nrest = classify_all(pool, block, bd, dedges)
        st["excluded by an allowed operation on P"] += nbridge
        st["classified as whole graphs"] += nrest
        folder = out / ("%s_%02d" % (case, c + 1))
        folder.mkdir(parents=True, exist_ok=True)
        recs = []
        for k, (G, o) in enumerate(zip(graphs, outcomes)):
            rec = {"id": "E22-%s-%06d" % (case, s0 + k), "case": case, "variant": "",
                   "graph": el.graph_record(G), "outcome": o}
            v = chk(G)
            if v is not None:
                rec["structural exclusion"] = v
            recs.append(rec)
        ext.finish_whole_item(
            "E22", recs,
            {case: {"specification": dict(spec.payload(), exterior="Psi3" + (" + bd" if bd else "")),
                    "parts in this folder": len(recs)}},
            [], folder, ext.SECTION6_STRUCT,
            "p1,p2 on abc; q1,q2 on ade; W on abcde; part %d of %s; the targets and the "
            "agreement are in the summary.json one folder up" % (c + 1, case), t0)
        st["folders"].append(folder.name)
        print(case, "folder", folder.name, nbridge, nrest, round(time.time() - t0), flush=True)
        del graphs, outcomes, recs
    st["seconds"] = round(time.time() - t0, 1)
    json.dump(st, open(out / ("%s_generation.json" % case), "w"), indent=1)
    pool.close()
